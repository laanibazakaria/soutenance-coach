export type Teinte = keyof typeof TEINTES;

/** Une icône en ligne, alignée sur le texte, de la couleur du texte. */
export function Icone({ nom, taille = 18, epaisseur = 1.8, className, style }: { nom: NomIcone; taille?: number; epaisseur?: number; className?: string; style?: CSSProperties }) {
  return (
    <svg
      className={className ? `icone ${className}` : "icone"}
      width={taille}
      height={taille}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={epaisseur}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      style={style}
    >
      {TRACES[nom]}
    </svg>
  );
}

/** Une pastille teintée avec l'icône au centre — en tête de carte, de ligne, de KPI. */
export function IconeBadge({ nom, teinte = "violet", taille = 40, rond = false, className }: { nom: NomIcone; teinte?: Teinte; taille?: number; rond?: boolean; className?: string }) {
  const t = TEINTES[teinte];
  return (
    <span
      className={className ? `icone-badge ${className}` : "icone-badge"}
      style={{ width: taille, height: taille, borderRadius: rond ? "50%" : Math.round(taille * 0.3), background: t.fond, color: t.trait }}
    >
      <Icone nom={nom} taille={Math.round(taille * 0.5)} />
    </span>
  );
}
